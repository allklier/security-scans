#!/usr/bin/env bash
# Build a throwaway local git repo with planted problems, one per layer, so the
# scanner can be shown to catch them (brief acceptance criterion 8).
#
#   tests/make-seeded-repo.sh            -> test-work/seeded-repo (recreated)
#
# Planted:
#   L1 deps     requirements.txt pins PyYAML==5.3 (CVE-2020-1747, CVE-2020-14343)
#   L2 malware  requirements.txt pins 0requests==0.0.1 (OpenSSF MAL-2026-15859)
#               NEVER pip-install this file.
#   L3 SAST     app.py: subprocess with shell=True on request data, yaml.load
#   L4 secrets  settings.py: fake GitHub token, committed then "removed" in a
#               later commit (still in history)
#   L5 config   .github/workflows/ci.yml: pull_request_target + PR-head checkout,
#               template injection, unpinned actions; Dockerfile runs as root
#
# The fake token is assembled at runtime so this script itself carries no
# secret-shaped string (keeps secret scanners quiet on the scanner repo).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$ROOT/test-work/seeded-repo}"
rm -rf "$DEST"; mkdir -p "$DEST"; cd "$DEST"
git init -q -b main
git config user.name "seeded-test"; git config user.email "seeded@example.invalid"
export GIT_AUTHOR_DATE="2026-01-01T00:00:00Z" GIT_COMMITTER_DATE="2026-01-01T00:00:00Z"

cat > README.md <<'MD'
# seeded-repo (TEST FIXTURE)
Deliberately insecure. Generated by security-scans/tests/make-seeded-repo.sh.
Do not install requirements.txt: it pins a known-malicious package.
MD

cat > requirements.txt <<'REQ'
# fully pinned (counts as a lockfile); DO NOT INSTALL
PyYAML==5.3
0requests==0.0.1
REQ

cat > app.py <<'PY'
import subprocess

import yaml
from flask import Flask, request

app = Flask(__name__)


@app.route("/run")
def run():
    cmd = request.args.get("cmd")
    return subprocess.check_output(cmd, shell=True)


@app.route("/load", methods=["POST"])
def load():
    return str(yaml.load(request.data))
PY

TOKEN="ghp_$(printf 'seeded-fake-token' | sha256sum | cut -c1-36)"
printf 'GITHUB_TOKEN = "%s"\n' "$TOKEN" > settings.py

mkdir -p .github/workflows
cat > .github/workflows/ci.yml <<'YML'
name: ci
on:
  pull_request_target:
jobs:
  build:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          ref: ${{ github.event.pull_request.head.sha }}
      - name: greet
        run: echo "PR title ${{ github.event.pull_request.title }}"
      - uses: some-org/some-action@main
YML

cat > Dockerfile <<'DF'
FROM python:3.12
COPY . /app
RUN pip install -r /app/requirements.txt
CMD ["python", "/app/app.py"]
DF

cat > .security-scans.toml <<'TOML'
# Accepted risks for this repo (read by security-scans).
[[accept]]
tool = "trivy"
rule = "DS-0026"
path = "Dockerfile"
reason = "Test fixture: no HEALTHCHECK needed"
expires = 2099-12-31

[[accept]]
tool = "zizmor"
rule = "zizmor/unpinned-uses"
path = ".github/workflows/ci.yml"
reason = "Test fixture: expired on purpose, must reappear"
expires = 2026-01-01
TOML

git add -A; git commit -q -m "seeded: initial insecure fixture"

# remove the secret from the working tree; it stays in history
export GIT_AUTHOR_DATE="2026-01-02T00:00:00Z" GIT_COMMITTER_DATE="2026-01-02T00:00:00Z"
printf 'import os\nGITHUB_TOKEN = os.environ.get("GITHUB_TOKEN", "")\n' > settings.py
git commit -q -am "seeded: move token to env (still in history)"
echo "seeded repo at $DEST ($(git rev-parse --short HEAD))"
